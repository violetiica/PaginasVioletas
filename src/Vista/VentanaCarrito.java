    private void tablaLibrosFisicosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaLibrosFisicosMouseClicked
        int row = tablaLibrosFisicos.rowAtPoint(evt.getPoint());
        if(row>=0){
            String codigo = (String)tablaLibrosFisicos.getValueAt(row, 0);
            String titulo = (String)tablaLibrosFisicos.getValueAt(row, 1);
            String autor = (String)tablaLibrosFisicos.getValueAt(row, 2);
            String genero = (String)tablaLibrosFisicos.getValueAt(row, 3);
            double precio = Double.parseDouble(tablaLibrosFisicos.getValueAt(row, 4).toString());
            String mensaje = "Codigo: "+codigo+" \n"+
                             "Titulo: "+titulo+" \n"+
                             "Autor: "+autor+" \n"+
                             "Genero: "+genero+" \n"+
                             "Precio: "+precio+"$"+" \n";
            String[] opciones = {"Volver","Eliminar del carrito"};
            int opc = JOptionPane.showOptionDialog(null, mensaje, "Detalles del Libro", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opciones, opciones[1]);
            switch(opc) {
                case 1: car.setLibrosF(carritoF);
                        Iterator<LibroFisico> it = carritoF.iterator();
                        LibroFisico eliminar = new LibroFisico();
                        while (it.hasNext()) {
                            LibroFisico libro = it.next();
                            if (libro.getTitulo() == titulo) {
                                eliminar = libro;
                            }
                        }  
                        eliminarLibroF(eliminar);
                        carritoF = car.getLibrosF();
                        VentanaCarrito ventana = new VentanaCarrito(car,carritoF,carritoD);
                        control.activaVentana(ventana, this);
                        //control.llenarTablaLibrosF(tablaLibrosFisicos, carritoF);
                        break;
            }
        }

    }//GEN-LAST:event_tablaLibrosFisicosMouseClicked

