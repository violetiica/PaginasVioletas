    private void btnBuscarLibroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarLibroMouseClicked
        ListSelectionModel selectionModel = tablaLibrosDigitales.getSelectionModel();
        selectionModel.clearSelection();
        boolean encontrado = false;
        String dato = JOptionPane.showInputDialog("Puede buscar libros por codigo, titulo, autor o genero. \n Ingrese el dato que desea buscar:");
        for (int i = 0; i < tablaLibrosDigitales.getRowCount(); i++) {
            for (int j = 0; j < tablaLibrosDigitales.getColumnCount(); j++) {
                String valor = tablaLibrosDigitales.getValueAt(i, j).toString();
                if (valor.equalsIgnoreCase(dato)) {
                    selectionModel.addSelectionInterval(i, i);
                    encontrado = true;
                }
            }
        }
        if (dato !=null && encontrado == false) {
             JOptionPane.showMessageDialog(null, "Libro no disponible", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarLibroMouseClicked

