    private void tablaLibrosDigitalesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaLibrosDigitalesMouseClicked
        int row = tablaLibrosDigitales.rowAtPoint(evt.getPoint());
        if(row>=0){
            String codigo = (String)tablaLibrosDigitales.getValueAt(row, 0);
            String titulo = (String)tablaLibrosDigitales.getValueAt(row, 1);
            String autor = (String)tablaLibrosDigitales.getValueAt(row, 2);
            String genero = (String)tablaLibrosDigitales.getValueAt(row, 3);
            double precio = Double.parseDouble(tablaLibrosDigitales.getValueAt(row, 4).toString());
            String formato = (String)tablaLibrosDigitales.getValueAt(row, 5);
            double tam = Double.parseDouble(tablaLibrosDigitales.getValueAt(row, 6).toString());
            String med = (String)tablaLibrosDigitales.getValueAt(row, 7);
            int ano = Integer.parseInt(tablaLibrosDigitales.getValueAt(row, 8).toString());
            int est = Integer.parseInt(tablaLibrosDigitales.getValueAt(row, 9).toString());
            int cant = Integer.parseInt(tablaLibrosDigitales.getValueAt(row, 10).toString());
            String mensaje = "Codigo: "+codigo+" \n"+
                             "Titulo: "+titulo+" \n"+
                             "Autor: "+autor+" \n"+
                             "Genero: "+genero+" \n"+
                             "Precio: "+precio+"$"+" \n"+
                             "Formato: "+formato+" \n"+
                             "Tamaño: "+tam+med+" \n"+
                             "Año de Publicación: "+ano+" \n"+
                             "Estado: "+est+" \n"+
                             "Cantidad Disponible: "+cant;
            String[] opciones = {"Volver","Eliminar del inventario"};
            int opc = JOptionPane.showOptionDialog(null, mensaje, "Detalles del Libro", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opciones, opciones[1]);
            switch(opc) {
                case 1: libroDigital.setLibrosDigitales(librosD);
                        Iterator<LibroDigital> it = librosD.iterator();
                        LibroDigital eliminar = new LibroDigital();
                        while (it.hasNext()) {
                            LibroDigital libro = it.next();
                            if (libro.getTitulo() == titulo) {
                                eliminar = libro;
                            }
                        }
                        libroDigital.eliminarLibroDigital(eliminar);
                        librosD = libroDigital.getLibrosDigitales();
                        VentanaLibrosDV ventana = new VentanaLibrosDV(libroFisico,libroDigital,librosF,librosD);
                        control.activaVentana(ventana, this);
                        break;
            }
        }
    }//GEN-LAST:event_tablaLibrosDigitalesMouseClicked

