    private void btnConfirmarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnConfirmarMouseClicked
        if (grupo1.getSelection() == null || grupo2.getSelection() == null) {
            //JOptionPane.showMessageDialog(null, "¡Debes seleccionar las opciones de envio!");
            JOptionPane.showMessageDialog(null, "Por favor, seleccione las opciones de envio.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
        control.calcularCostoEnvio(nacional, internacional, normal, urgente);
        costoEnvio = control.getCostoEnvio();
        VentanaComprar ventana = new VentanaComprar(totalCar,costoEnvio);
        control.activaVentana(ventana, this);
        }
    }//GEN-LAST:event_btnConfirmarMouseClicked

