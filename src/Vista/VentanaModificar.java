    private void btnModificarLibroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnModificarLibroMouseClicked
        if (codigotxt.getText().startsWith("F")) {
            Iterator<LibroFisico> it = librosF.iterator();
            LibroFisico modificar = new LibroFisico();
            boolean continuar = true;
            while (it.hasNext()) {
                LibroFisico libro = it.next();
                    if (libro.getCodigo().equalsIgnoreCase(codigotxt.getText())) {
                        modificar = libro;
                        continuar = false;
                    }
            }
            if (continuar == true) {
                JOptionPane.showMessageDialog(null, "Libro no registrado", "Errores de Validacion", JOptionPane.ERROR_MESSAGE);  
            } else {
               VentanaModificarFisico ventana = new VentanaModificarFisico(libroFisico,libroDigital,librosF,librosD,modificar);
               control.activaVentana(ventana, this);
            }
        } else if (codigotxt.getText().startsWith("D")) {
            Iterator<LibroDigital> it = librosD.iterator();
            LibroDigital modificar = new LibroDigital();
            boolean continuar = true;
            while (it.hasNext()) {
                LibroDigital libro = it.next();
                    if (libro.getCodigo().equalsIgnoreCase(codigotxt.getText())) {
                        modificar = libro;
                        continuar = false;
                    }
            }
            if (continuar == true) {
                JOptionPane.showMessageDialog(null, "Libro no registrado", "Errores de Validacion", JOptionPane.ERROR_MESSAGE);  
            } else {
                VentanaModificarDigital ventana = new VentanaModificarDigital(libroFisico,libroDigital,librosF,librosD,modificar);
               control.activaVentana(ventana, this);
            }
        } else {
            JOptionPane.showMessageDialog(null, "Ingrese un codigo valido", "Errores de Validacion", JOptionPane.ERROR_MESSAGE); 
        }
    }//GEN-LAST:event_btnModificarLibroMouseClicked

