    public boolean validarLimite(double num, double lim1, double lim2) {
        boolean error = false;
        if (num < lim1 || num > lim2) {
            error = true;
        }
        return error;
    }
    public boolean validarCodigo(String codigo) { 
        boolean error = false;
        if (!codigo.startsWith("F")) {
            error = true;
            errores.append("- El codigo del libro debe empezar con F mayuscula.\n");
        }
        return error; 
    }
    public boolean validarAutor(String autor) { 
        boolean error = false;
        if (!autor.matches("[a-zA-Z ]+")) {
            error = true;
            errores.append("- El nombre del autor debe contener solo letras.\n");
        }
        return error;
    }
    public boolean validarGenero(String genero, StringBuilder errores) { 
        boolean error = false;
        if (genero == null || genero.equals("Seleccione un genero")) {
            error = true;
            errores.append("- Debe seleccionar un genero.\n");
        }
        return error;
    }
    
