    private void btnAgregarFMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnAgregarFMouseClicked
        errores.setLength(0);
        errorCodigo.setForeground(Color.white);
        errorTitulo.setForeground(Color.white);
        errorAutor.setForeground(Color.white);
        errorGenero.setForeground(Color.white);
        errorPeso.setForeground(Color.white);
        errorAno.setForeground(Color.white);
        errorCosto.setForeground(Color.white);
        errorGanancia.setForeground(Color.white);
        if(validarCodigo(codigotxt.getText())) {
            errorCodigo.setForeground(Color.red);
        }
        if(validarAutor(autortxt.getText())){
            errorAutor.setForeground(Color.red);
        }
       if(validarGenero(comboGeneros.getSelectedItem().toString(),errores)){
           //errores.append("- Debe seleccionar un genero.\n");
           errorGenero.setForeground(Color.red);
       }
        try {
            if(validarLimite(Integer.parseInt(anotxt.getText()),1810,2024)){
                errores.append("- El año debe ser entre 1810 y 2024.\n");
                errorAno.setForeground(Color.red);
            }
        } catch (NumberFormatException ex) {
            errores.append("- Ingrese un año valido.\n");
            errorAno.setForeground(Color.red);
        }   
        try {
            if(validarLimite(Double.parseDouble(pesotxt.getText()),0,1)){
                errores.append("- El peso debe ser maximo 1kg.\n");
                errorPeso.setForeground(Color.red);
            }
        } catch(NumberFormatException ex) {
            errores.append("- Ingrese un peso valido.\n");
            errorPeso.setForeground(Color.red);
        }
        try {
            if(validarLimite(Double.parseDouble(costotxt.getText()),30,100)){
                errores.append("- El costo debe ser entre 30$ y 100$.\n");
                errorCosto.setForeground(Color.red);
            }
        } catch (NumberFormatException ex) {
            errores.append("- Ingrese un costo valido.\n");
            errorCosto.setForeground(Color.red);
        }
        try {
            if(validarLimite(Double.parseDouble(gananciatxt.getText()),0,50)){
                errores.append("- La ganancia debe ser maximo 50%.\n");
                errorGanancia.setForeground(Color.red);
            }
        } catch (NumberFormatException ex){
            errores.append("- Ingrese una ganancia valido.\n");
            errorGanancia.setForeground(Color.red);
        }
        try {
            if(validarLimite(Integer.parseInt(cantidadtxt.getText()),0,35)){
                errores.append("- La cantidad debe ser maximo 35.\n");
                errorCantidad.setForeground(Color.red);
            }
        } catch (NumberFormatException ex) {
            errores.append("- Ingrese una cantidad valida.\n");
            errorCantidad.setForeground(Color.red);
        }
                
        if (errores.length() > 0) {
            JOptionPane.showMessageDialog(null, errores.toString(), "Errores de Validacion", JOptionPane.ERROR_MESSAGE); 
            
        } else {
            int estado = (Integer.parseInt(cantidadtxt.getText()) >= 1) ? 1 : 0;
            LibroFisico lf = new LibroFisico();
            lf.calcularPrecioLibro(Double.parseDouble(gananciatxt.getText()),Double.parseDouble(costotxt.getText()));
            double precio = lf.getPrecio();
            LibroFisico libro = new LibroFisico(Double.parseDouble(pesotxt.getText()),codigotxt.getText(),titulotxt.getText(),autortxt.getText(),(String)comboGeneros.getSelectedItem(),Integer.parseInt(cantidadtxt.getText()),Integer.parseInt(anotxt.getText()),estado,precio,Double.parseDouble(costotxt.getText()));
            Iterator<LibroFisico> it = libroFisico.getLibrosFisicos().iterator();
            boolean continuar = false;
            while (it.hasNext() && continuar == false) {
                LibroFisico lib = it.next();
                if (lib.getCodigo().equalsIgnoreCase(codigotxt.getText())) {
                    errorCodigo.setForeground(Color.red);
                    JOptionPane.showMessageDialog(null, "El codigo "+lib.getCodigo()+" ya esta registrado");
                    continuar = true;
                } else if (lib.getTitulo().equalsIgnoreCase(titulotxt.getText())) {
                    errorTitulo.setForeground(Color.red);
                    JOptionPane.showMessageDialog(null, "El libro "+lib.getTitulo()+" ya esta registrado");
                    continuar = true;
                }
            }
            if(continuar==false) {
                libroFisico.agregarLibroFisico(libro);
                JOptionPane.showMessageDialog(null, "¡Libro agregado correctamente!");
                limpiarDatos();
            }
        }
    }//GEN-LAST:event_btnAgregarFMouseClicked

