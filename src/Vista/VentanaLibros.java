    private void btnBuscarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarMouseClicked
        ListSelectionModel selectionModel = tablaLibrosFisicos.getSelectionModel();
        selectionModel.clearSelection();
        boolean encontrado = false;
        String dato = JOptionPane.showInputDialog("Puede buscar libros por codigo, titulo, autor o genero. \n Ingrese el dato que desea buscar:");
        for (int i = 0; i < tablaLibrosFisicos.getRowCount(); i++) {
            for (int j = 0; j < tablaLibrosFisicos.getColumnCount(); j++) {
                String valor = tablaLibrosFisicos.getValueAt(i, j).toString();
                if (valor.equalsIgnoreCase(dato)) {
                    selectionModel.addSelectionInterval(i, i);
                    encontrado = true;
                }
            }
        }
        if (dato !=null && encontrado == false) {
             JOptionPane.showMessageDialog(null, "Libro no disponible", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarMouseClicked

